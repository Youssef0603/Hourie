export type Subcontractor = {
  id: number;
  name: string;
  contact_name: string | null;
  phone: string | null;
  email: string | null;
  tax_number: string | null;
};

export type SubcontractItem = {
  id: number;
  position: number;
  code: string | null;
  description: string;
  unit: string;
  /** Quantity in the original contract (0 for items added by a variation). */
  quantity: string;
  /** Contract quantity plus every variation. */
  authorized_quantity: string;
  /** Cumulative quantity of the last approved valuation. */
  executed_quantity: string;
  unit_price: string;
  /** Variation that added this item, e.g. "AV-01". */
  variation: string | null;
  /** "arh": ARH buys the materials and the subcontractor is paid for labour. */
  materials_supplied_by: MaterialsSuppliedBy;
  materials: SubcontractItemMaterial[];
};

export type MaterialsSuppliedBy = "subcontractor" | "arh";

export type SubcontractItemMaterial = {
  id: number;
  name: string;
  unit: string;
  /** Quantity of material one unit of work consumes, e.g. 7 bags per m³. */
  quantity_per_unit: string;
  waste_percent: string;
};

export type MaterialCheckStatus = "ok" | "surplus" | "shortfall";

/** Material ARH bought for a work item compared with what the executed work needed. */
export type MaterialCheck = {
  item_id: number;
  code: string;
  description: string;
  unit: string;
  executed_quantity: string;
  materials: Array<{
    id: number;
    name: string;
    unit: string;
    quantity_per_unit: string;
    waste_percent: string;
    theoretical_quantity: string;
    needed_quantity: string;
    bought_quantity: string;
    bought_amount: string;
    gap_quantity: string;
    gap_amount: string;
    status: MaterialCheckStatus;
    purchase_orders: Array<{ id: number; number: string; quantity: string; pdf_url: string }>;
  }>;
};

export type SubcontractVariation = {
  id: number;
  reference: string;
  title: string;
  reason: string | null;
  approved_on: string;
  amount: string;
  lines: Array<{ subcontract_item_id: number; description: string; unit: string; quantity: string }>;
};

export type ValuationStatus = "draft" | "submitted" | "approved" | "partially_paid" | "paid";

export type PaymentMethod = "transfer" | "cheque" | "cash";

/** "advance": the start advance; "opening": everything certified before Hourie. */
export type ValuationKind = "regular" | "advance" | "opening";

/** Payment channels followed separately: cash, cheque or transfer before VAT, and VAT. */
export type PaymentChannel = "cash" | "cheque" | "vat";

export type ChannelAmounts = { due: string; paid: string; balance: string };

export type ValuationPayment = {
  id: number;
  amount: string;
  /** Part of a cheque or transfer that pays VAT. */
  vat_amount: string;
  paid_on: string;
  method: PaymentMethod | null;
  reference: string | null;
  notes: string | null;
  recorded_by: string | null;
};

export type SubcontractValuationSummary = {
  id: number;
  reference: string;
  kind: ValuationKind;
  status: ValuationStatus;
  valuation_date: string;
  period_end: string;
  net_due: string;
  paid_amount: string;
  balance_due: string;
  invoice_amount: string | null;
  invoice_matches: boolean;
};

export type Subcontract = {
  id: number;
  reference: string;
  title: string;
  status: string;
  signed_on: string | null;
  subcontractor: Subcontractor;
  project: { id: number; code: string | null; name: string };
  vat_rate: string;
  retention_rate: string;
  advance_amount: string;
  advance_recovery_rate: string;
  /** Share of every amount paid in cash, without VAT. */
  cash_percent: string;
  /** Fixed amount taken off every situation, e.g. "Coupe pavé". */
  recurring_deduction_label: string | null;
  recurring_deduction_amount: string;
  /** Works certified before Hourie without a breakdown by work item. */
  historical_works_amount: string;
  currency: string;
  notes: string | null;
  summary: {
    original_amount: string;
    variations_amount: string;
    revised_amount: string;
    executed_amount: string;
    progress_percent: number;
    paid_amount: string;
    to_pay_amount: string;
    retention_held: string;
    advance_remaining: string;
    channels: Record<PaymentChannel, ChannelAmounts>;
    /** True once a situation or an opening balance exists (the advance does not count). */
    has_work_valuations: boolean;
    valuations_count: number;
    open_valuation: { id: number; reference: string; status: ValuationStatus } | null;
  };
  items: SubcontractItem[];
  variations?: SubcontractVariation[];
  valuations: SubcontractValuationSummary[];
  material_check?: MaterialCheck[];
  /** Purchase orders that bought material for this subcontract. */
  purchase_orders?: LinkedPurchaseOrder[];
};

export type LinkedPurchaseOrder = { id: number; number: string; supplier_name: string; ordered_on: string; pdf_url: string };

export type SubcontractItemInput = {
  key: string;
  id?: number;
  /** Generated by the server ({site code}-{sequence}); read-only. */
  code: string;
  description: string;
  unit: string;
  quantity: string;
  unit_price: string;
  materials_supplied_by: MaterialsSuppliedBy;
  materials: MaterialInput[];
};

export type MaterialInput = { key: string; id?: number; name: string; unit: string; quantity_per_unit: string; waste_percent: string };

export type SubcontractPayload = {
  subcontractor_id: number | null;
  project_id: number | null;
  title: string;
  signed_on: string;
  vat_rate: string;
  retention_rate: string;
  advance_amount: string;
  advance_recovery_rate: string;
  cash_percent: string;
  recurring_deduction_label: string;
  recurring_deduction_amount: string;
  currency: string;
  notes: string;
  items: Array<Omit<SubcontractItemInput, "key" | "code" | "materials"> & { materials: Array<Omit<MaterialInput, "key">> }>;
};

export type VariationPayload = {
  title: string;
  reason: string;
  approved_on: string;
  lines: Array<{ subcontract_item_id: number; quantity: string }>;
  new_items: Array<{
    description: string;
    unit: string;
    quantity: string;
    unit_price: string;
    materials_supplied_by: MaterialsSuppliedBy;
    materials: Array<Omit<MaterialInput, "key" | "id">>;
  }>;
};

export type ValuationLine = {
  subcontract_item_id: number;
  code: string | null;
  description: string;
  unit: string;
  unit_price: string;
  authorized_quantity: string;
  previous_quantity: string;
  cumulative_quantity: string;
  period_quantity: string;
  /** Where the work of the period was done, e.g. "P40 - P59". */
  location: string | null;
  period_amount: string;
  cumulative_amount: string;
};

export type SubcontractValuation = {
  id: number;
  reference: string;
  sequence: number;
  kind: ValuationKind;
  status: ValuationStatus;
  valuation_date: string;
  period_end: string;
  comment: string | null;
  materials_deduction: string;
  backcharges: string;
  cash_percent: string;
  subcontract: {
    id: number;
    reference: string;
    title: string;
    subcontractor: string;
    project: { id: number; code: string | null; name: string };
    currency: string;
    retention_rate: string;
    advance_amount: string;
    advance_recovery_rate: string;
    vat_rate: string;
    cash_percent: string;
  };
  lines: ValuationLine[];
  calculation: {
    works_cumulative: string;
    /** Part of the cumulative works certified before Hourie without a breakdown. */
    historical_works: string;
    works_previous: string;
    works_this_period: string;
    advance_recovery_cumulative: string;
    advance_recovery_this_period: string;
    retention_cumulative: string;
    retention_this_period: string;
    certified_cumulative: string;
    previously_certified: string;
    this_valuation_before_vat: string;
    materials_deduction: string;
    backcharges: string;
    net_before_vat: string;
    cash_amount: string;
    cheque_amount: string;
    vat_amount: string;
    net_due: string;
    advance_remaining: string;
  };
  /** Only regular situations with a cheque part need the subcontractor's invoice. */
  requires_invoice: boolean;
  /** Amount the invoice must show: cheque part plus VAT. */
  invoice_expected: string;
  invoice: { number: string; date: string; amount: string; matches: boolean; difference: string } | null;
  channels: Record<PaymentChannel, ChannelAmounts>;
  paid_amount: string;
  balance_due: string;
  payments: ValuationPayment[];
  documents: Array<{ id: number; type: "statement" | "invoice"; url: string; original_name: string; size_bytes: number; created_at: string }>;
  approved_by: string | null;
  approved_at: string | null;
  paid_at: string | null;
};

